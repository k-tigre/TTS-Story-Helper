package by.tigre.speechhelper.data

/**
 * Общие системные промпты для LLM-разметки текста под SpeechKit ([voice]…[/voice], паузы).
 * Используются [AiMarkupApi] и [OpenAiMarkupApi].
 */
object MarkupSystemPrompts {

    private val baseAutoMarkupPrompt = """
        Задача: подготовить текст для озвучки Yandex SpeechKit — расставить голоса и при необходимости паузы.

        Формат голосов: [voice_id]фрагмент[/voice_id]. Каждую открывающую метку обязательно закрывай парной [/voice_id].

        Паузы только так: <[tiny]>, <[small]>, <[medium]>, <[large]>, <[huge]> — внутри содержимого одного голоса, на естественных паузах. Не вставляй паузу между открывающим [voice_id] и закрывающим [/voice_id] одной пары.

        Имена voice_id — латиница, цифры и подчёркивание (voice_main, voice_actor, voice_elder_woman). Рассказчик: voice_main, нейтрально, без эмоциональных пометок в тексте. Другие id — для прямой речи персонажей в диалогах; один персонаж — одно стабильное имя голоса.

        Диалоги: реплика (включая тире) — в голос персонажа; примыкающие слова автора («объяснил он», «ответила она», причастные обороты за тире) — в voice_main.

        Пример:
        Исходный фрагмент:
        — Это система подачи, — объяснил парень, видя растерянное лицо Тёмы. — Она слепая как крот. Если зазеваешься — прищемит так, что мало не покажется. Ты тот самый Серебряков?

        Разметка:
        [voice_actor]
        — Это система подачи, —
        [/voice_actor]
        [voice_main]
        объяснил парень, видя растерянное лицо Тёмы.
        [/voice_main]
        [voice_actor]
        Она слепая как крот. Если зазеваешься — прищемит так, что мало не покажется. Ты тот самый Серебряков?
        [/voice_actor]

        Если во входе несколько абзацев подряд разделены одной пустой строкой, в ответе сохрани столько же абзацев с теми же разделителями (пустая строка между блоками).

        Жёстко: не меняй слова, знаки препинания и порядок смысловых фрагментов исходника. Выведи только размеченный текст, без пояснений и без markdown (без блоков ```).
    """.trimIndent()

    val dialogFixPrompt: String = """
        Проверь размеченный текст. Слова автора в диалогах (например «сказал он», «ответила она», «пробормотал он, отступая») должны быть в голосе рассказчика [voice_main], а не внутри метки голоса персонажа.

        Не меняй слова и знаки исходника — только границы меток [voice_id]…[/voice_id]; все пары тегов должны остаться корректно закрытыми.

        Пример НЕПРАВИЛЬНОЙ разметки:
        [voice_actor]
        — Я не понимаю, о чём вы, — пробормотал он, отступая на шаг.
        [/voice_actor]

        Пример ПРАВИЛЬНОЙ разметки:
        [voice_actor]
        — Я не понимаю, о чём вы, —
        [/voice_actor]
        [voice_main]
        пробормотал он, отступая на шаг.
        [/voice_main]

        Исправь все такие места. Верни ТОЛЬКО исправленный размеченный текст, без пояснений.
    """.trimIndent()

    fun autoMarkupPrompt(existingVoices: Set<String>): String {
        if (existingVoices.isEmpty()) return baseAutoMarkupPrompt
        val voicesList = existingVoices.joinToString(", ")
        return buildString {
            append(baseAutoMarkupPrompt)
            append("\n\nВ книге уже используются следующие голоса: ")
            append(voicesList)
            append(". Используй те же имена для разметки; новые id добавляй только для новых персонажей, если это необходимо.")
        }
    }
}
